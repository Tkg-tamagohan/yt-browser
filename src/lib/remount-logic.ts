// リマウント回避（常時マウント化）したパネルの「開くたびに取り直す」を
// 再現するための純粋ロジック（FR-80、仕様決定 DE）。
//
// webkit2gtk のヒットずれ対策でパネルを常時マウント＋hidden 切替にすると、
// これまで「開くとマウントされる」ことに乗っていた onMount 時の取得が
// 走らなくなる。そこで可視状態と取り直しの対象キーから「取得を起こす
// キー」を解決し、呼び出し側は $effect 内で戻り値を前回値と比較して
// 変化したときだけ再取得する。

/// 可視状態から取得キーを解決する。
/// - 非表示（visible=false）の間は常に null を返す。閉じている間に
///   key が変わっても戻り値は null のままなので取り直しは起きず、
///   開き直した時点のキーで 1 回だけ取得が走る
/// - 表示中に key が変わると戻り値も変わるため、その都度の取り直しに
///   なる（概要欄パネルの再生中動画切替への追従など）
/// - 「開いたときだけ取り直す」用途（関連動画・統計タブなど、開いて
///   いる間に対象が変わらないもの）には呼び出し側が固定キーを渡す
export function panelFetchKey(
  visible: boolean,
  key: string,
): string | null {
  return visible ? key : null;
}
