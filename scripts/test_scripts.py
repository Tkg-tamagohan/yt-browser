def _ws_send_frame(conn: socket.socket, opcode: int, payload: bytes) -> None:
    n = len(payload)
    header = bytearray([0x80 | opcode])
    if n < 126:
        header.append(n)
    elif n < 65536:
        header.append(126)
        header.extend(struct.pack("!H", n))
    else:
        header.append(127)
        header.extend(struct.pack("!Q", n))
    conn.sendall(bytes(header) + payload)


def _ws_recv_frame(conn: socket.socket) -> tuple[int, bytes] | None:
    def exact(k: int) -> bytes | None:
        buf = bytearray()
        while len(buf) < k:
            chunk = conn.recv(k - len(buf))
            if not chunk:
                return None
            buf.extend(chunk)
        return bytes(buf)

    head = exact(2)
    if head is None:
        return None
    opcode = head[0] & 0x0F
    masked = (head[1] & 0x80) != 0
    length = head[1] & 0x7F
    if length == 126:
        ext = exact(2)
        if ext is None:
            return None
        length = struct.unpack("!H", ext)[0]
    elif length == 127:
        ext = exact(8)
        if ext is None:
            return None
        length = struct.unpack("!Q", ext)[0]
    mask = exact(4) if masked else b"\x00\x00\x00\x00"
    if mask is None:
        return None
    raw = exact(length)
    if raw is None:
        return None
    if masked:
        raw = bytes(b ^ mask[i % 4] for i, b in enumerate(raw))
    return opcode, raw


class TestCdpAndE2eHelpers(unittest.TestCase):
    """SC-07〜SC-09: cdp_client / e2e_dev / e2e_smoke の動作確認。"""

    def test_sc07_pick_page_target_and_mock_websocket_session(self) -> None:
        targets = [
            {"type": "background_page", "url": "http://localhost:1420/bg"},
            {"type": "page", "url": "http://localhost:1420/"},
            {"type": "page", "url": "http://localhost:1420/settings"},
        ]
        self.assertEqual(
            cdp_client.pick_page_target(targets)["url"],
            "http://localhost:1420/",
        )
        self.assertEqual(
            cdp_client.pick_page_target(targets, url_contains="/settings")["url"],
            "http://localhost:1420/settings",
        )
        self.assertIsNone(cdp_client.pick_page_target([]))
        # url_contains が一致しない場合は先頭の page ターゲットにフォールバックする
        self.assertEqual(
            cdp_client.pick_page_target(targets, url_contains="/not-found")["url"],
            "http://localhost:1420/",
        )

        # RFC 6455 ローカルモックサーバーを起動して CdpSession を通信検証する
        srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        srv.bind(("127.0.0.1", 0))
        srv.listen(1)
        port = srv.getsockname()[1]

        def serve() -> None:
            conn, _ = srv.accept()
            with conn:
                req = b""
                while b"\r\n\r\n" not in req:
                    chunk = conn.recv(4096)
                    if not chunk:
                        return
                    req += chunk
                key = ""
                for line in req.decode("latin1").split("\r\n"):
                    if line.lower().startswith("sec-websocket-key:"):
                        key = line.split(":", 1)[1].strip()
                accept = base64.b64encode(
                    hashlib.sha1(
                        (key + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11").encode("ascii")
                    ).digest()
                ).decode("ascii")
                conn.sendall(
                    (
                        "HTTP/1.1 101 Switching Protocols\r\n"
                        "Upgrade: websocket\r\n"
                        "Connection: Upgrade\r\n"
                        f"Sec-WebSocket-Accept: {accept}\r\n\r\n"
                    ).encode("ascii")
                )

                # 先行イベントを 1 件プッシュしたあとコマンド応答を返す
                _ws_send_frame(
                    conn,
                    0x1,
                    json.dumps({"method": "Runtime.consoleAPICalled", "params": {"type": "log"}}).encode("utf-8"),
                )
                while True:
                    frame = _ws_recv_frame(conn)
                    if frame is None or frame[0] == 0x8:
                        break
                    if frame[0] != 0x1:
                        continue
                    msg = json.loads(frame[1].decode("utf-8"))
                    cid = msg["id"]
                    method = msg["method"]
                    if method == "Runtime.evaluate":
                        expr = msg["params"]["expression"]
                        val = "fail" if expr == "fail_cmd" else f"eval:{expr}"
                        if expr == "throw_cmd":
                            reply = {
                                "id": cid,
                                "result": {
                                    "result": {"type": "undefined"},
                                    "exceptionDetails": {"text": "boom"},
                                },
                            }
                        else:
                            reply = {
                                "id": cid,
                                "result": {"result": {"type": "string", "value": val}},
                            }
                    elif method == "Error.cmd":
                        reply = {"id": cid, "error": {"code": -32000, "message": "mock error"}}
                    else:
                        reply = {"id": cid, "result": {"ok": True}}
                    _ws_send_frame(conn, 0x1, json.dumps(reply).encode("utf-8"))

        t = threading.Thread(target=serve, daemon=True)
        t.start()
        try:
            sess = cdp_client.CdpSession(f"ws://127.0.0.1:{port}/devtools/page/1", timeout=5.0)
            try:
                self.assertEqual(sess.command("Page.enable"), {"ok": True})
                self.assertEqual(sess.evaluate("1+1"), "eval:1+1")
                events = sess.drain_events()
                self.assertTrue(any(ev.get("method") == "Runtime.consoleAPICalled" for ev in events))
                with self.assertRaises(cdp_client.CdpError):
                    sess.command("Error.cmd")
                with self.assertRaises(cdp_client.CdpError):
                    sess.evaluate("throw_cmd")
            finally:
                sess.close()
        finally:
            srv.close()
            t.join(timeout=2.0)

