def _create_valid_dist(
    dist: Path,
    repo: str = "owner/yt-browser",
    tag: str = "v1.2.3",
    appimage_name: str = "yt-browser_1.2.3_amd64.AppImage",
    exe_name: str = "yt-browser_1.2.3_x64-setup.exe",
    extra_ext_files: dict[str, str] | None = None,
) -> None:
    dist.mkdir(parents=True, exist_ok=True)
    (dist / appimage_name).write_bytes(b"appimage")
    _write_text(dist / f"{appimage_name}.sig", "sig-linux\n")
    (dist / exe_name).write_bytes(b"exe")
    _write_text(dist / f"{exe_name}.sig", "sig-win\n")
    (dist / f"yt-browser_1.2.3_amd64.deb").write_bytes(b"deb")
    (dist / f"yt-browser-1.2.3-1.x86_64.rpm").write_bytes(b"rpm")
    manifest = make_latest_json.build_manifest(
        repo, tag, dist, pub_date="2026-01-01T00:00:00Z"
    )
    _write_text(dist / "latest.json", json.dumps(manifest, indent=2) + "\n")
    (dist / f"{appimage_name}.sig").unlink()
    (dist / f"{exe_name}.sig").unlink()

    ext_zip = dist / f"yt-browser-extension-{tag}.zip"
    with zipfile.ZipFile(ext_zip, "w") as zf:
        zf.writestr("manifest.json", json.dumps({"manifest_version": 3, "name": "test"}))
        zf.writestr("shared.js", "export const x = 1;\n")
        for rel, body in (extra_ext_files or {}).items():
            zf.writestr(rel, body)


class TestCiChanges(unittest.TestCase):
    """SC-01: ci_changes のパス分類・正規化・出力形式。"""

    def test_sc01_classification_matrix(self) -> None:
        # docs / meta のみはすべて False
        self.assertEqual(
            ci_changes.classify_paths(
                [
                    "docs/requirements-definition.md",
                    "./README.md",
                    "AGENTS.md",
                    "LICENSE",
                    "scripts\\README.md",
                    ".devin/skills/sample/SKILL.md",
                    ".vscode/settings.json",
                ]
            ),
            {"run_frontend": False, "run_rust": False, "run_windows": False},
        )
        # docs/design.md を含む場合は rust のみ True（DDL 照合テスト担保）
        self.assertEqual(
            ci_changes.classify_paths(["docs/design.md", "README.md"]),
            {"run_frontend": False, "run_rust": True, "run_windows": False},
        )
        # コード・ワークフロー・スクリプトの変更はすべて True
        for path in [
            "src/routes/+page.svelte",
            "src-tauri/src/lib.rs",
            "scripts/ci_changes.py",
            ".github/workflows/ci.yml",
            "extension/popup.js",
            "package.json",
        ]:
            with self.subTest(path=path):
                self.assertEqual(
                    ci_changes.classify_paths([path]),
                    {"run_frontend": True, "run_rust": True, "run_windows": True},
                )
        # None / 空列はフェイルセーフで全 True
        for empty in (None, [], [""]):
            self.assertEqual(
                ci_changes.classify_paths(empty),
                {"run_frontend": True, "run_rust": True, "run_windows": True},
            )

